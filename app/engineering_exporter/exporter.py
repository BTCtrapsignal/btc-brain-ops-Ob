def generate_timeline(week: str, session: Session) -> str:
    """
    Cross-system engineering timeline.

    PENDING: Source Review #5 (app/api/reflex.py) is required before
    implementing cross-system timeline assembly. The Reflex observation
    persistence model in Brain Ops must be confirmed before Reflex events
    can be joined with Signal Bot events by timestamp.

    Signal Bot events (from EventLog) are included as a partial timeline.
    Reflex observation correlation is deferred.
    """
    events = session.exec(
        select(EventLog)
        .where(EventLog.week == week)
        .order_by(EventLog.event_ts)
    ).all()

    out = _doc_header(week, f"Engineering Timeline — {week}")
    out += "> **Note:** Cross-system Reflex correlation is pending Source Review #5 (reflex.py).\n"
    out += "> This timeline currently shows Signal Bot events only.\n\n"
    out += "---\n\n"
    out += "## Signal Bot Event Timeline\n\n"

    if not events:
        out += "*No events recorded for this week.*\n"
        return out

    out += "| Timestamp | Source | Event Type | Signal | Detail |\n"
    out += "|---|---|---|---|---|\n"
    for ev in events:
        signal_ref = f"[[Signal-{ev.signal_id}]]" if ev.signal_id else "—"
        detail = ev.reason or ev.state_to or ev.result or "—"
        out += (
            f"| {_safe_iso(ev.event_ts)[:19]} "
            f"| {ev.source or '—'} "
            f"| {ev.event_type} "
            f"| {signal_ref} "
            f"| {detail[:60]} |\n"
        )

    out += f"\n*{len(events)} events. Reflex correlation: pending.*\n"
    return out


