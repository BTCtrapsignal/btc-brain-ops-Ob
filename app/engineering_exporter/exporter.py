# generate_eo_register
# ─────────────────────────────────────────────────────────────

def generate_eo_register(week: str, session: Session) -> str:
    """
    Export all Engineering Observations from Brain Ops database.
    Includes full lifecycle state and evidence counts.
    """
    # All EOs — not week-filtered, as EOs span multiple sprints
    eos = session.exec(
        select(EngineeringObservation).order_by(EngineeringObservation.eo_id)
    ).all()

    out = _doc_header(week, f"Engineering Observation Register — {week}")
    out += "Brain Ops is the authoritative store for Engineering Observations.\n\n"
    out += f"Total EOs: **{len(eos)}**\n\n"

    if not eos:
        out += "*No Engineering Observations recorded yet.*\n"
        return out

    # Status summary
    by_status: dict = {}
    for eo in eos:
        by_status[eo.status] = by_status.get(eo.status, 0) + 1

    out += "## Status Summary\n\n"
    out += "| Status | Count |\n|---|---|\n"
    for status, count in sorted(by_status.items()):
        out += f"| {status} | {count} |\n"
    out += "\n---\n\n"

    out += "## Engineering Observations\n\n"
    for eo in eos:
        out += f"### [[{eo.eo_id}]] — {eo.title}\n\n"
        out += f"| Field | Value |\n|---|---|\n"
        out += f"| EO ID | `{eo.eo_id}` |\n"
        out += f"| Layer | {eo.layer or '—'} |\n"
        out += f"| Sprint Opened | {eo.sprint_opened or '—'} |\n"
        out += f"| Status | **{eo.status}** |\n"
        out += f"| Confidence | {eo.confidence or '—'} |\n"
        out += f"| Evidence Count | {eo.evidence_count} |\n"
        out += f"| Linked ER | {f'[[{eo.linked_er_id}]]' if eo.linked_er_id else '—'} |\n"
        out += f"| Monitoring Expires | {_safe_iso(eo.monitoring_window_expires)} |\n\n"
        if eo.hypothesis:
            out += f"**Hypothesis:** {eo.hypothesis}\n\n"
        if eo.trigger_condition:
            out += f"**Trigger:** {eo.trigger_condition}\n\n"
        if eo.exit_criteria:
            out += f"**Exit Criteria:** {eo.exit_criteria}\n\n"
        if eo.notes:
            out += f"**Notes:** {eo.notes}\n\n"
        out += "---\n\n"

    return out


