# generate_runtime_statistics
# ─────────────────────────────────────────────────────────────

def generate_runtime_statistics(week: str, session: Session) -> str:
    """
    Aggregated runtime statistics as JSON.
    Covers signals, events, missed opportunities, and lifecycle data.
    WAIT/FILTER_FAIL counts: pending W27 Runtime Validation (REQ-W27-001 data).
    """
    signals = session.exec(select(Signal).where(Signal.week == week)).all()
    events  = session.exec(select(EventLog).where(EventLog.week == week)).all()
    missed  = session.exec(select(MissedOpportunity).where(MissedOpportunity.week == week)).all()

    # Signal stats
    wins   = sum(1 for s in signals if s.result == "WIN")
    losses = sum(1 for s in signals if s.result == "LOSS")
    open_  = sum(1 for s in signals if s.result == "OPEN")
    wr     = round(wins / len(signals) * 100, 1) if signals else 0.0

    # PnL
    net_pnl = sum(s.net_pnl_usd or 0 for s in signals)

    # Event breakdown
    event_type_counts: dict = {}
    for ev in events:
        event_type_counts[ev.event_type] = event_type_counts.get(ev.event_type, 0) + 1

    # Rejection reasons
    rejection_reasons: dict = {}
    for mo in missed:
        reason = mo.rejection_reason or "unknown"
        rejection_reasons[reason] = rejection_reasons.get(reason, 0) + 1

    # Duration (signals with entry and exit)
    durations = []
    for s in signals:
        if s.signal_ts and s.exit_ts:
            delta = (s.exit_ts - s.signal_ts).total_seconds() / 3600
            durations.append(delta)
    avg_duration_h = round(sum(durations) / len(durations), 1) if durations else None

    stats = {
        "schema_version":  SCHEMA_VERSION,
        "package_version": f"{PACKAGE_VERSION_PREFIX}.0",
        "generated_at":    datetime.now(timezone.utc).isoformat(),
        "generator":       "Brain Ops",
        "runtime_version": COMPATIBLE_RUNTIME,
        "week":            week,
        "signals": {
            "total":        len(signals),
            "wins":         wins,
            "losses":       losses,
            "open":         open_,
            "win_rate_pct": wr,
            "net_pnl_usd":  round(net_pnl, 2),
            "avg_duration_hours": avg_duration_h,
        },
        "events": {
            "total":       len(events),
            "by_type":     event_type_counts,
        },
        "missed_opportunities": {
            "total":            len(missed),
            "rejection_reasons": rejection_reasons,
        },
        "filter_decisions": {
            "note": (
                "WAIT and FILTER_FAIL counts pending W27 Runtime Validation. "
                "REQ-W27-001 structured logs available in Signal Bot Railway logs."
            ),
        },
    }
    return json.dumps(stats, indent=2, default=str)


