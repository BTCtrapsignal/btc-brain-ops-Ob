def generate_engineering_summary(week: str, session: Session) -> str:
    """
    Executive engineering summary for the week.
    Covers verified findings, open investigations, promotion candidates,
    and pending runtime validation items.
    """
    eos = session.exec(select(EngineeringObservation)).all()
    ers = session.exec(select(EngineeringReview)).all()
    evidence = session.exec(select(EngineeringEvidence)).all()

    # Classify
    open_eos  = [eo for eo in eos if eo.status in ("open", "monitoring")]
    closed_eos = [eo for eo in eos if eo.status == "closed"]

    promoted_ers   = [er for er in ers if er.status == "promoted"]
    candidate_ers  = [er for er in ers if er.status == "candidate"]
    open_ers       = [er for er in ers if er.status in ("draft", "evidence_collecting")]
    closed_ers     = [er for er in ers if er.status == "closed"]

    pos_evidence = sum(1 for ev in evidence if ev.evidence_type == "positive")
    neg_evidence = sum(1 for ev in evidence if ev.evidence_type == "negative")

    out = _doc_header(week, f"Engineering Summary — {week}")
    out += "Brain Ops — Authoritative Engineering Evidence Warehouse\n\n"
    out += "---\n\n"

    out += "## Health Metrics\n\n"
    out += "| Metric | Value |\n|---|---|\n"
    out += f"| Total EOs | {len(eos)} |\n"
    out += f"| Open EOs | {len(open_eos)} |\n"
    out += f"| Closed EOs | {len(closed_eos)} |\n"
    out += f"| Total ERs | {len(ers)} |\n"
    out += f"| Promoted ERs | {len(promoted_ers)} |\n"
    out += f"| Candidate ERs | {len(candidate_ers)} |\n"
    out += f"| Open ERs | {len(open_ers)} |\n"
    out += f"| Closed ERs | {len(closed_ers)} |\n"
    out += f"| Positive Evidence | {pos_evidence} |\n"
    out += f"| Negative Evidence | {neg_evidence} |\n"
    if pos_evidence + neg_evidence > 0:
        neg_ratio = round(neg_evidence / (pos_evidence + neg_evidence) * 100, 1)
        out += f"| Negative Evidence Ratio | {neg_ratio}% |\n"
    out += "\n---\n\n"

    if promoted_ers:
        out += "## Promoted Engineering Reviews\n\n"
        for er in promoted_ers:
            out += f"- [[{er.er_id}]] — {er.title}"
            if er.verified_finding:
                out += f": {er.verified_finding[:100]}"
            out += "\n"
        out += "\n---\n\n"

    if candidate_ers:
        out += "## Promotion Candidates\n\n"
        out += "> Promotion decisions belong to Engineering Review (ChatGPT) — Article 9.\n\n"
        for er in candidate_ers:
            out += f"- [[{er.er_id}]] — {er.title} (confidence={er.confidence or '?'})\n"
        out += "\n---\n\n"

    if open_ers:
        out += "## Open Engineering Reviews\n\n"
        for er in open_ers:
            out += (
                f"- [[{er.er_id}]] — {er.title} "
                f"(status={er.status}, evidence={er.evidence_count}/{er.negative_evidence_count})\n"
            )
        out += "\n---\n\n"

    if open_eos:
        out += "## Active Engineering Observations\n\n"
        for eo in open_eos:
            out += f"- [[{eo.eo_id}]] — {eo.title} (evidence={eo.evidence_count})\n"
        out += "\n---\n\n"

    out += "## Pending Runtime Validation\n\n"
    out += (
        "- WAIT / FILTER_FAIL event mirroring: Pending W27 Runtime Validation\n"
        "- Cross-system Reflex timeline: Pending Source Review #5 (reflex.py)\n"
        "- Obsidian wiki link extension: Pending Source Review #4 (formatter.py)\n\n"
    )
    out += "---\n\n"
    out += f"*Engineering Summary — {week} — Generated by Brain Ops*\n"
    return out
