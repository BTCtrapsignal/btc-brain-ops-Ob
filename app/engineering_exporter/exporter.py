# ─────────────────────────────────────────────────────────────

def generate_event_bundle(week: str, session: Session) -> str:
    """
    Machine-readable engineering event stream as JSON.
    Every event from EventLog for the week, with version metadata.
    """
    events = session.exec(
        select(EventLog)
        .where(EventLog.week == week)
        .order_by(EventLog.event_ts)
    ).all()

    bundle = {
        "schema_version":  SCHEMA_VERSION,
        "package_version": f"{PACKAGE_VERSION_PREFIX}.0",
        "generated_at":    datetime.now(timezone.utc).isoformat(),
        "generator":       "Brain Ops",
        "runtime_version": COMPATIBLE_RUNTIME,
        "week":            week,
        "event_count":     len(events),
        "events": [
            {
                "id":             ev.id,
                "timestamp":      _safe_iso(ev.event_ts),
                "source":         ev.source,
                "event_type":     ev.event_type,
                "signal_id":      ev.signal_id,
                "direction":      ev.direction,
                "result":         ev.result,
                "state_from":     ev.state_from,
                "state_to":       ev.state_to,
                "reason":         ev.reason,
                "event_metadata": ev.event_metadata,
            }
            for ev in events
        ],
    }
    return json.dumps(bundle, indent=2, default=str)


