def _doc_header(week: str, title: str, generator_version: str = "Brain Ops") -> str:
    """Standard engineering document header with version metadata."""
    now = datetime.now(timezone.utc).isoformat()
    return (
        f"---\n"
        f"Engineering Package Version : {PACKAGE_VERSION_PREFIX}.0\n"
        f"Schema Version               : {SCHEMA_VERSION}\n"
        f"Generator                    : {generator_version}\n"
        f"Generated At                 : {now}\n"
        f"Compatible Runtime           : {COMPATIBLE_RUNTIME}\n"
        f"Week                         : {week}\n"
        f"---\n\n"
        f"# {title}\n\n"
    )


def _safe_iso(dt: Optional[datetime]) -> str:
    if dt is None:
        return "—"
    return dt.isoformat()


