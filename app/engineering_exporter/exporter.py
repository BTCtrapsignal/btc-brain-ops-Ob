def generate_engineering_index(week: str, session: Session) -> str:
    """
    Landing page for the weekly engineering package.
    Lists all available documents with internal links.
    """
    signals = session.exec(select(Signal).where(Signal.week == week)).all()
    eos = session.exec(
        select(EngineeringObservation).where(EngineeringObservation.sprint_opened == week)
    ).all()
    ers = session.exec(
        select(EngineeringReview).where(EngineeringReview.sprint_opened == week)
    ).all()
    events = session.exec(select(EventLog).where(EventLog.week == week)).all()

    out = _doc_header(week, f"Engineering Index — {week}")
    out += "This is the primary entry point for the weekly engineering package.\n\n"
    out += "---\n\n"
    out += "## Document Index\n\n"
    out += f"| Document | Content |\n"
    out += f"|---|---|\n"
    out += f"| [[Weekly-Summary]] | Trading intelligence summary |\n"
    out += f"| [[Runtime-Evidence]] | Chronological runtime evidence |\n"
    out += f"| [[Timeline]] | Cross-system engineering timeline |\n"
    out += f"| [[Signal-Lifecycle]] | Per-signal lifecycle export |\n"
    out += f"| [[EO-Register]] | Engineering Observations |\n"
    out += f"| [[ER-Register]] | Engineering Reviews |\n"
    out += f"| [[Engineering-Observations]] | Auto-generated behavioural observations |\n"
    out += f"| [[Runtime-Statistics]] | Aggregated runtime statistics |\n"
    out += f"| [[Engineering-Summary]] | Executive summary and findings |\n\n"
    out += "---\n\n"
    out += "## Week at a Glance\n\n"
    out += f"| Metric | Count |\n"
    out += f"|---|---|\n"
    out += f"| Signals | {len(signals)} |\n"
    out += f"| Events logged | {len(events)} |\n"
    out += f"| Engineering Observations | {len(eos)} |\n"
    out += f"| Engineering Reviews | {len(ers)} |\n\n"

    if signals:
        wins = sum(1 for s in signals if s.result == "WIN")
        losses = sum(1 for s in signals if s.result == "LOSS")
        out += f"| Wins | {wins} |\n"
        out += f"| Losses | {losses} |\n\n"

    out += "---\n\n"
    out += "## Navigation\n\n"
    out += f"← Previous week: [[{week}-prev]]  \n"
    out += f"→ Next week: [[{week}-next]]  \n\n"
    out += f"*Generated by Brain Ops — {week}*\n"
    return out


